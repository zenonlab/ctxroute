// MUTATION-SCOPE-PURE — what the mutation workflow and the purity rule MUST say,
// DERIVED from the two lists that carry real knowledge. Zero I/O.
// ═══════════════════════════════════════════════════════════════════════
//
// 🔴 WHY IT EXISTS (23/09/2026): adding one mutated module meant FIVE hand edits —
//    `stryker.conf.json` `mutate`, `vitest.stryker.config.mjs` `include`, the
//    `paths:` of `.github/workflows/mutation.yml` (module AND suite), a
//    `*-must-stay-pure` rule in `.dependency-cruiser.json`, and its `includeOnly`
//    entry. Gates caught an omission, but every agent still had to KNOW the five
//    places. And the fourth had quietly stopped being written: MEASURED that day,
//    25 of the 55 mutated modules had NO purity rule at all — "pure" by name, with
//    nothing refusing `require('fs')` tomorrow.
// 🔑 TWO LISTS ARE KNOWLEDGE, THE REST IS DERIVED: `mutate` says WHICH modules are
//    measured, `include` says WHICH suites measure them — a human decides both. The
//    workflow's `paths:` and the purity rule only REPEAT them, so they are GENERATED
//    here and written by `tools/mutation-scope.js --write`; a gate reddens when the
//    written files drift from what this module computes.
// 🛑 A PURITY EXEMPTION IS WRITTEN, WITH ITS REASON, never an omission: an exempted
//    module is one a reader must be told about, and an exemption nobody still needs
//    is REFUSED (a dormant permit widens the rule's hole for free).
// ⚠️ PURE AND MUTATED: the generated text decides what CI watches and what the
//    architecture gate refuses. Written in the I/O shell it would be measured by nothing.
// ═══════════════════════════════════════════════════════════════════════

'use strict';

// The files whose change can move a mutation score without being a module or a suite.
// ⚠️ A FUNCTION, never a module-level literal (a load-time literal is a static mutant).
function configFiles() {
  return ['stryker.conf.json', 'vitest.stryker.config.mjs', 'package.json', 'package-lock.json', '.github/workflows/mutation.yml'];
}

// The INDEPENDENT MODELS the Stryker suites confront the engine with. Deliberately NOT
// mutated (mutating a model measures its differential's domain, not its quality), yet a
// change to one moves the score of what IS mutated — so the workflow must see it.
function modelFiles() {
  return ['src/language-spec.js', 'src/cadence-spec.js'];
}

const BLOCK_OPEN = '      # AUTO:mutation-scope — GENERATED by tools/mutation-scope.js from stryker.conf.json `mutate` and vitest.stryker.config.mjs `include`. NEVER edit by hand: node tools/mutation-scope.js --write';
const BLOCK_CLOSE = '      # /AUTO:mutation-scope';

/**
 * The `paths:` lines of the mutation workflow: every mutated module, every suite that
 * measures one, then the configuration itself — in that order, each list in its own order.
 * @param {string[]} mutate
 * @param {string[]} include
 * @returns {string}
 */
function workflowBlock(mutate, include) {
  const entries = mutate.concat(include, modelFiles(), configFiles());
  const lines = entries.map((p) => `      - '${p}'`);
  return [BLOCK_OPEN].concat(lines, [BLOCK_CLOSE]).join('\n');
}

/**
 * Replace the generated block inside the workflow text. A workflow WITHOUT the markers is
 * a NAMED REFUSAL: guessing where the block goes could rewrite the wrong trigger.
 * @param {string} workflow
 * @param {string} block
 * @returns {string}
 */
function spliceWorkflow(workflow, block) {
  // ⚠️ The closing marker is searched AFTER the opening one: a close found before the open
  //    is then simply "not found", with no second comparison to get wrong.
  const start = workflow.indexOf(BLOCK_OPEN);
  const end = workflow.indexOf(BLOCK_CLOSE, start);
  if (start === -1 || end === -1) {
    throw new Error('mutation-scope: the AUTO:mutation-scope markers are missing from the mutation workflow — refusing to guess where its paths live');
  }
  return workflow.slice(0, start) + block + workflow.slice(end + BLOCK_CLOSE.length);
}

const RULE_NAME = 'mutated-modules-must-stay-pure';

// The mutated modules the purity rule deliberately does NOT cover, each with its reason.
// 🛑 Adding one is a DECISION a reader must see; a module listed here that is no longer
//    mutated is refused by `dormantExemptions`.
function purityExemptions() {
  return {
    'src/kernel-endpoint.js': 'it COMPUTES the OS rendezvous address (a named pipe, an abstract socket or a socket file), so it reads `os` and `path` by design — measured 23/09/2026, the only mutated module that does. Its decisions stay mutated; only the import rule does not apply.',
  };
}

/**
 * The ONE purity rule covering every mutated module that is not exempted IN WRITING.
 * Same shape as the per-module rules already in `.dependency-cruiser.json`.
 * @param {string[]} mutate
 * @param {Object<string,string>} exempt - module → written reason
 */
function purityRule(mutate, exempt) {
  const covered = mutate.filter((m) => !(m in exempt));
  const alternatives = covered.map((m) => m.replace(/\./g, '\\.'));
  return {
    name: RULE_NAME,
    comment: 'GENERATED by tools/mutation-scope.js from stryker.conf.json `mutate` (23/09/2026): a mutated module is PURE, so it may never reach the disk, the path layer or a process. Exemptions are written, with their reason, in purityExemptions() of src/mutation-scope-pure.js — never an omission.',
    severity: 'error',
    from: { path: `^(${alternatives.join('|')})$` },
    to: { path: '^(fs|path|child_process)$', dependencyTypes: ['core'] },
  };
}

/**
 * Exemptions naming a module that is no longer mutated: a dormant permit.
 * @param {string[]} mutate
 * @param {Object<string,string>} exempt
 * @returns {string[]}
 */
function dormantExemptions(mutate, exempt) {
  const mutated = new Set(mutate);
  return Object.keys(exempt).filter((m) => !mutated.has(m));
}

/**
 * Put the generated rule in place of the previous one (or append it the first time),
 * leaving every hand-written rule untouched and in its order.
 * @param {{forbidden: Array<{name: string}>}} cruiser - parsed .dependency-cruiser.json
 * @param {{name: string}} rule
 */
function spliceRule(cruiser, rule) {
  const kept = cruiser.forbidden.filter((r) => r.name !== RULE_NAME);
  return { ...cruiser, forbidden: kept.concat([rule]) };
}

module.exports = { configFiles, modelFiles, workflowBlock, spliceWorkflow, purityRule, purityExemptions, dormantExemptions, spliceRule, BLOCK_OPEN, BLOCK_CLOSE, RULE_NAME };
